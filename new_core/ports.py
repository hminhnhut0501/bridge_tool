from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Protocol, Sequence


@dataclass(frozen=True, slots=True)
class KickResult:
    ok: bool
    reason: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)


class Clock(Protocol):
    def now(self) -> datetime: ...


class OrderRepository(Protocol):
    def list_expiry_candidates(self, *, before: datetime, limit: int) -> Sequence[dict[str, Any]]: ...
    def get_order(self, order_id: str) -> dict[str, Any] | None: ...
    def update_status(self, order_id: str, status: str, *, changed_at: datetime) -> dict[str, Any] | None: ...


class KickTaskRepository(Protocol):
    def get_task(self, order_id: str, user_id: str) -> dict[str, Any] | None: ...
    def create_task(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def create_group_task(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def update_task(self, task_id: str, payload: dict[str, Any]) -> dict[str, Any] | None: ...
    def list_due_group_tasks(self, *, before: datetime, limit: int) -> Sequence[dict[str, Any]]: ...
    def update_group_task(self, group_task_id: str, payload: dict[str, Any]) -> dict[str, Any] | None: ...


class MembershipGateway(Protocol):
    async def is_present(self, group_id: str, user_id: str) -> bool | None: ...
    async def kick(self, group_id: str, user_id: str) -> KickResult: ...
    async def mute(self, group_id: str, user_id: str) -> KickResult: ...
    async def unmute(self, group_id: str, user_id: str) -> KickResult: ...


class NotificationGateway(Protocol):
    async def send_expiry_notice(self, user_id: str, payload: dict[str, Any]) -> bool: ...
    async def send_reminder(self, user_id: str, payload: dict[str, Any]) -> bool: ...


class LegacyEventSink(Protocol):
    def append(self, event_type: str, user_id: str, *, payload: dict[str, Any] | None = None) -> None: ...
